export function convertParameterValueForExport(options: ConvertParameterOptions): ConvertParameterResult {
  const { inputValue, parameterDef } = options;
  const warnings: string[] = [];

  let mode = (options.conversionMode || parameterDef?.transform || parameterDef?.conversion?.mode || parameterDef?.translationMode || parameterDef?.conversion || "direct") as string;
  if (mode === "gain_db") mode = "db_to_linear";

  let val = inputValue;
  if (val === undefined || val === null || val === "") {
    val = parameterDef?.defaultValue ?? parameterDef?.defaultDisplayValue ?? 0;
  }

  const valStr = String(val).trim();
  const valStrLower = valStr.toLowerCase();

  // Option rows & valueMap handling for enums/switches
  if (parameterDef) {
    if (parameterDef.optionRows && Array.isArray(parameterDef.optionRows)) {
      const match = parameterDef.optionRows.find((r: any) =>
        String(r.displayLabel).trim().toLowerCase() === valStrLower ||
        String(r.canonicalValue).trim().toLowerCase() === valStrLower
      );
      if (match && match.exportValue !== undefined) {
        val = match.exportValue;
      }
    } else if (parameterDef.valueMap && typeof parameterDef.valueMap === "object") {
      const keys = Object.keys(parameterDef.valueMap);
      const matchKey = keys.find(k => k.trim().toLowerCase() === valStrLower);
      if (matchKey !== undefined) {
        val = parameterDef.valueMap[matchKey];
      }
    }
  }

  // Unit
  let rawUnit = options.displayUnit ?? parameterDef?.displayUnit ?? parameterDef?.unit ?? "";
  if (rawUnit.toLowerCase() === "linear" && (mode === "db_to_linear" || mode === "dbThresholdToLinear")) {
    rawUnit = "dB";
  }
  const unit = rawUnit || (
    mode === "db_to_linear" || mode === "dbThresholdToLinear" || mode === "noiseGateDepth" || mode === "linear_to_db" ? "dB" : ""
  );

  // Decimal places for export and display formatting
  const isLinearFloatMode = mode === "db_to_linear" || mode === "dbThresholdToLinear" || mode === "black76InputOutput" || mode === "linear_to_db";

  // Export Range
  const authoritativeMin = parameterDef?.authoritativeRange?.[0];
  const authoritativeMax = parameterDef?.authoritativeRange?.[1];

  let expMin: number;
  let expMax: number;

  if (authoritativeMin !== undefined && authoritativeMax !== undefined && (parameterDef?.definitionSource === "db_mapping" || parameterDef?.definitionSource === "verified_override")) {
    expMin = authoritativeMin;
    expMax = authoritativeMax;
    if (options.exportMin !== undefined && options.exportMax !== undefined && (options.exportMin !== expMin || options.exportMax !== expMax)) {
      console.warn(
        `[AT5 Exporter Resolution Priority] Authoritative range [${expMin}, ${expMax}] from ${parameterDef.definitionSource} takes precedence over options bounds [${options.exportMin}, ${options.exportMax}] for parameter "${parameterDef.friendlyName || parameterDef.xmlName}".`
      );
    }
  } else {
    expMin = options.exportMin ?? parameterDef?.exportMin ?? parameterDef?.export?.min ?? parameterDef?.min ?? (mode === "db_to_linear" ? 0.177828 : 0);
    expMax = options.exportMax ?? parameterDef?.exportMax ?? parameterDef?.export?.max ?? parameterDef?.max ?? (mode === "db_to_linear" ? 5.62341 : 1);
  }

  const actualExpMin = Math.min(expMin, expMax);
  const actualExpMax = Math.max(expMin, expMax);

  const isSubOneExportRange = actualExpMax <= 1.05 && mode !== "boolean" && mode !== "enum";

  // Precision resolution: Display precision vs Export precision
  const rawDispPrec = options.displayPrecision ?? options.displayDecimalPlaces ?? parameterDef?.displayPrecision ?? parameterDef?.displayDecimalPlaces ?? parameterDef?.decimalPlaces;
  const isDiscrete = mode === "boolean" || mode === "enum" || parameterDef?.parameterKind === "boolean" || parameterDef?.parameterKind === "enum" || parameterDef?.parameterKind === "selector";
  const dispPrecision: number = rawDispPrec !== undefined && rawDispPrec !== null ? Math.max(0, Math.round(Number(rawDispPrec))) : (isDiscrete ? 0 : 2);

  const rawExpPrec = options.exportPrecision ?? options.exportDecimalPlaces ?? parameterDef?.exportPrecision ?? parameterDef?.exportDecimalPlaces;
  const explicitExpPrecision = rawExpPrec !== undefined && rawExpPrec !== null ? Math.max(0, Math.round(Number(rawExpPrec))) : undefined;

  let decPlaces: number;
  if (explicitExpPrecision !== undefined) {
    decPlaces = explicitExpPrecision;
  } else if (isLinearFloatMode || isSubOneExportRange) {
    // Float modes and small linear export ranges require 6 decimal places to prevent truncation to 0
    decPlaces = 6;
  } else if (parameterDef?.decimalPlaces !== undefined) {
    decPlaces = Math.max(0, Math.round(Number(parameterDef.decimalPlaces)));
  } else {
    decPlaces = 6;
  }

  if (isLinearFloatMode && decPlaces < 6 && explicitExpPrecision === undefined) {
    decPlaces = 6;
  }

  // Display Range
  let dMin = options.displayMin ?? parameterDef?.displayMin ?? parameterDef?.visualMin ?? parameterDef?.visual?.min;
  let dMax = options.displayMax ?? parameterDef?.displayMax ?? parameterDef?.visualMax ?? parameterDef?.visual?.max;

  if (mode === "db_to_linear") {
    if (dMin === undefined || dMax === undefined || (dMin === expMin && dMax === expMax) || (dMin >= 0 && dMax > 1 && dMax <= 10)) {
      if (parameterDef?.displayMin !== undefined && parameterDef?.displayMax !== undefined && (parameterDef.displayMin !== expMin || parameterDef.displayMax !== expMax)) {
        dMin = parameterDef.displayMin;
        dMax = parameterDef.displayMax;
      } else {
        dMin = -15;
        dMax = 15;
      }
    }
  } else if (mode === "dbThresholdToLinear") {
    dMin = -100;
    dMax = 0;
  } else {
    if (dMin === undefined) dMin = 0;
    if (dMax === undefined) dMax = (mode === "scaled_range" ? 10 : expMax);
  }

  const displayMin = Math.min(dMin, dMax);
  const displayMax = Math.max(dMin, dMax);

  // Parse numeric
  let numVal: number | undefined;
  if (typeof val === "number") {
    numVal = val;
  } else {
    const match = valStr.match(/-?\d+(?:\.\d+)?(?:e-?\d+)?/i);
    if (match) {
      numVal = parseFloat(match[0]);
    }
  }

  const formattedVisualMin = displayMin.toFixed(dispPrecision);
  const formattedVisualMax = displayMax.toFixed(dispPrecision);
  const formattedExportMin = explicitExpPrecision !== undefined ? actualExpMin.toFixed(explicitExpPrecision) : (isLinearFloatMode ? actualExpMin.toFixed(6) : String(actualExpMin));
  const formattedExportMax = explicitExpPrecision !== undefined ? actualExpMax.toFixed(explicitExpPrecision) : (isLinearFloatMode ? actualExpMax.toFixed(6) : String(actualExpMax));

  // Non-numeric fallback (e.g. enum strings "Low", "All")
  if (numVal === undefined || !Number.isFinite(numVal)) {
    return {
      inputValue,
      inputDisplayValue: valStr,
      conversionMode: mode,
      displayUnit: unit,
      displayMin,
      displayMax,
      displayClampApplied: false,
      clampedDisplayValue: valStr,
      convertedRawValue: 0,
      exportMin: actualExpMin,
      exportMax: actualExpMax,
      rawClampApplied: false,
      clampApplied: false,
      finalExportValue: 0,
      formattedExportValue: valStr,
      reverseDisplayValue: valStr,
      displayPrecision: dispPrecision,
      exportPrecision: explicitExpPrecision,
      formattedVisualMin,
      formattedVisualMax,
      formattedExportMin,
      formattedExportMax,
      warnings: []
    };
  }

  const inputDisplayVal = numVal;
  let clampedDisplayVal = numVal;
  let displayClampApplied = false;
  let rawVal = numVal;
  let clampedRawVal = numVal;
  let rawClampApplied = false;

  if (mode === "db_to_linear") {
    // 1. Clamp display dB value to display range
    if (numVal < displayMin || numVal > displayMax) {
      clampedDisplayVal = Math.min(displayMax, Math.max(displayMin, numVal));
      displayClampApplied = true;
      warnings.push(`Input display value was clamped from ${numVal} dB to ${clampedDisplayVal} dB.`);
    } else {
      clampedDisplayVal = numVal;
    }
    // 2. Convert dB to raw linear value
    rawVal = Math.pow(10, clampedDisplayVal / 20);

    // 3. Clamp raw linear value to export range
    if (rawVal < actualExpMin || rawVal > actualExpMax) {
      clampedRawVal = Math.min(actualExpMax, Math.max(actualExpMin, rawVal));
      if (Math.abs(clampedRawVal - rawVal) > 1e-5) {
        rawClampApplied = true;
        warnings.push(`Converted raw linear value ${rawVal.toFixed(6)} was clamped to export bounds [${actualExpMin}, ${actualExpMax}].`);
      } else {
        clampedRawVal = rawVal;
      }
    } else {
      clampedRawVal = rawVal;
    }
  } else if (mode === "dbThresholdToLinear") {
    // Negative threshold control (-100 to 0 dB)
    if (numVal < -100 || numVal > 0) {
      clampedDisplayVal = Math.min(0, Math.max(-100, numVal));
      displayClampApplied = true;
      warnings.push(`Threshold dB value ${numVal >= 0 ? "+" + numVal : numVal} dB was clamped to threshold bounds [-100, 0] dB (${clampedDisplayVal} dB).`);
    } else {
      clampedDisplayVal = numVal;
    }
    rawVal = Math.pow(10, clampedDisplayVal / 20);
    if (rawVal < actualExpMin || rawVal > actualExpMax) {
      clampedRawVal = Math.min(actualExpMax, Math.max(actualExpMin, rawVal));
      if (Math.abs(clampedRawVal - rawVal) > 1e-5) {
        rawClampApplied = true;
        warnings.push(`Converted raw linear value ${rawVal.toFixed(6)} was clamped to export bounds [${actualExpMin}, ${actualExpMax}].`);
      } else {
        clampedRawVal = rawVal;
      }
    } else {
      clampedRawVal = rawVal;
    }
  } else if (mode === "linear_to_db") {
    const db = numVal <= 0 ? -100 : 20 * Math.log10(numVal);
    rawVal = Math.min(actualExpMax, Math.max(actualExpMin, db));
    clampedRawVal = rawVal;
  } else if (mode === "scaled_range") {
    const span = displayMax - displayMin;
    const pct = span === 0 ? 0 : (numVal - displayMin) / span;
    const clampedPct = Math.min(1, Math.max(0, pct));
    if (clampedPct !== pct) {
      displayClampApplied = true;
    }
    rawVal = actualExpMin + clampedPct * (actualExpMax - actualExpMin);
    clampedRawVal = Math.min(actualExpMax, Math.max(actualExpMin, rawVal));
  } else if (mode === "khzToHzIfNeeded") {
    let hz = numVal;
    if (valStrLower.includes("khz")) hz *= 1000;
    rawVal = Math.min(actualExpMax, Math.max(actualExpMin, hz));
    clampedRawVal = rawVal;
  } else if (mode === "noiseGateRelease") {
    let ms = numVal;
    if (valStrLower.includes("s") && !valStrLower.includes("ms")) ms *= 1000;
    else if (numVal > 1.5 && numVal <= 10) ms = 20 + numVal * 148;
    else if (numVal <= 1.5) ms *= 1000;
    rawVal = Math.min(actualExpMax, Math.max(actualExpMin, ms));
    clampedRawVal = rawVal;
  } else if (mode === "noiseGateDepth") {
    let depth = numVal;
    if (!valStrLower.includes("db") && numVal >= 0 && numVal <= 10) depth = -100 + numVal * 8;
    rawVal = Math.min(actualExpMax, Math.max(actualExpMin, depth));
    clampedRawVal = rawVal;
  } else if (mode === "black76InputOutput") {
    let db = numVal;
    if (db > 0) db = 0;
    if (db < -99) db = -99;
    rawVal = Math.pow(10, db / 20);
    clampedRawVal = Math.min(actualExpMax, Math.max(actualExpMin, rawVal));
  } else {
    // Direct
    if (numVal < actualExpMin || numVal > actualExpMax) {
      clampedRawVal = Math.min(actualExpMax, Math.max(actualExpMin, numVal));
      rawClampApplied = true;
      warnings.push(`Input value ${numVal} was clamped to export bounds [${actualExpMin}, ${actualExpMax}].`);
    } else {
      clampedRawVal = numVal;
    }
    rawVal = numVal;
  }

  const clampApplied = displayClampApplied || rawClampApplied;
  const finalVal = clampedRawVal;

  let formatted = "";
  if (explicitExpPrecision !== undefined) {
    formatted = finalVal.toFixed(explicitExpPrecision);
  } else if (Math.abs(finalVal - Math.round(finalVal)) < 1e-7 && !isLinearFloatMode && actualExpMin >= 1) {
    formatted = String(Math.round(finalVal));
  } else if (Math.abs(finalVal) < 1e-9 && (mode === "db_to_linear" || mode === "dbThresholdToLinear")) {
    formatted = "0";
  } else {
    const fixedStr = finalVal.toFixed(decPlaces);
    formatted = parseFloat(fixedStr).toString();
    if (formatted === "0" && Math.abs(finalVal) > 1e-7) {
      formatted = parseFloat(finalVal.toFixed(6)).toString();
    }
  }

  let reverseDisplay = "";
  if (mode === "db_to_linear" || mode === "dbThresholdToLinear") {
    const revDb = 20 * Math.log10(Math.max(1e-6, finalVal));
    const signStr = revDb >= 0 ? "+" : "";
    reverseDisplay = `${signStr}${revDb.toFixed(dispPrecision)} dB`;
  } else if (mode === "linear_to_db") {
    const revLin = Math.pow(10, finalVal / 20);
    reverseDisplay = revLin.toFixed(dispPrecision);
  } else if (mode === "scaled_range") {
    const span = actualExpMax - actualExpMin;
    const pct = span === 0 ? 0 : (finalVal - actualExpMin) / span;
    const revDisp = displayMin + pct * (displayMax - displayMin);
    reverseDisplay = `${revDisp.toFixed(dispPrecision)}${unit ? ' ' + unit : ''}`.trim();
  } else if (unit) {
    if (typeof clampedDisplayVal === "number") {
      reverseDisplay = `${clampedDisplayVal.toFixed(dispPrecision)} ${unit}`.trim();
    } else {
      reverseDisplay = `${clampedDisplayVal} ${unit}`.trim();
    }
  } else {
    if (typeof clampedDisplayVal === "number") {
      reverseDisplay = clampedDisplayVal.toFixed(dispPrecision);
    } else {
      reverseDisplay = String(clampedDisplayVal);
    }
  }

  return {
    inputValue,
    inputDisplayValue: inputDisplayVal,
    parsedNumericValue: numVal,
    conversionMode: mode,
    displayUnit: unit,
    displayMin,
    displayMax,
    displayClampApplied,
    clampedDisplayValue: clampedDisplayVal,
    convertedRawValue: rawVal,
    exportMin: actualExpMin,
    exportMax: actualExpMax,
    rawClampApplied,
    clampApplied,
    finalExportValue: finalVal,
    formattedExportValue: formatted,
    reverseDisplayValue: reverseDisplay,
    displayPrecision: dispPrecision,
    exportPrecision: explicitExpPrecision,
    formattedVisualMin,
    formattedVisualMax,
    formattedExportMin,
    formattedExportMax,
    warnings
  };
}

export interface ParameterVerificationResult {
  match: boolean;
  status: "SUCCESS" | "SUCCESS_NEAREST_BAND" | "DISPARITY" | "WARNING" | "FAIL" | "FAIL_MAPPING_CONFIGURATION" | "MISMATCH";
  reason?: string;
  warning?: string;
  isAccidentalClampingTo1: boolean;
  isMappingConfigSuspicious: boolean;
  toleranceUsed: number;
}

export function verifyParameterExportMatch(options: {
  intendedDisplayValue: string | number;
  expectedExportValue: string | number;
  actualExportValue: string | number | undefined;
  parameterDef?: ResolvedParameter | any;
  conversionResult?: ConvertParameterResult;
  isNearestBandMapping?: boolean;
  nearestBandFreq?: number;
}): ParameterVerificationResult {
  const {
    intendedDisplayValue,
    expectedExportValue,
    actualExportValue,
    parameterDef,
    conversionResult,
    isNearestBandMapping,
    nearestBandFreq,
  } = options;

  // 1. Check for missing actual export value
  if (actualExportValue === undefined || actualExportValue === "MISSING" || actualExportValue === null || String(actualExportValue).trim() === "") {
    return {
      match: false,
      status: "FAIL",
      reason: `Expected ${intendedDisplayValue} (raw: ${expectedExportValue}) but parameter "${parameterDef?.xmlName || parameterDef?.friendlyName || 'unknown'}" is missing in exported XML.`,
      warning: undefined,
      isAccidentalClampingTo1: false,
      isMappingConfigSuspicious: false,
      toleranceUsed: 0,
    };
  }

  // 2. Check for accidental continuous knob clamping down to 1
  const isKnownContinuousAmpKnob = parameterDef?.kind === "continuous_knob" || 
    (parameterDef?.max > 1 && inferParameterKind(parameterDef?.friendlyName, parameterDef?.xmlName) === "continuous_knob") ||
    (inferParameterKind(parameterDef?.friendlyName, parameterDef?.xmlName) === "continuous_knob");

  const isAccidentalClampingTo1 = !!(isKnownContinuousAmpKnob && parameterDef?.max === 1 && conversionResult?.clampApplied);

  if (isAccidentalClampingTo1) {
    return {
      match: false,
      status: "FAIL",
      reason: `Accidental continuous knob clamping: Intended display: ${intendedDisplayValue}, clamped to ${expectedExportValue} because exportMax is ${parameterDef?.max}`,
      warning: `Input value ${intendedDisplayValue} was clamped to ${expectedExportValue} because exportMax is 1. This appears invalid for a continuous amp knob.`,
      isAccidentalClampingTo1: true,
      isMappingConfigSuspicious: false,
      toleranceUsed: 0,
    };
  }

  // 3. Numeric extraction & comparison
  const nv = typeof expectedExportValue === "number" ? expectedExportValue : parseFloat(String(expectedExportValue));
  const ev = typeof actualExportValue === "number" ? actualExportValue : parseFloat(String(actualExportValue));
  const displayNum = typeof intendedDisplayValue === "number" ? intendedDisplayValue : parseFloat(String(intendedDisplayValue));

  let isMappingConfigSuspicious = false;
  let match = false;
  let toleranceUsed = 0.05;

  if (!isNaN(nv) && !isNaN(ev)) {
    // Check if actual XML value matched intended display directly but mapping wanted a drastically different value
    if (!isNaN(displayNum) && Math.abs(displayNum - ev) <= 0.15 && Math.abs(nv - ev) > 0.5 && Math.abs(displayNum) > 1e-4) {
      // Intended display equals actual exported XML, but mapping was different
      isMappingConfigSuspicious = true;
      match = false;
    } else {
      // Determine parameter scale and calculate scale-appropriate tolerance
      const expMin = parameterDef?.min ?? conversionResult?.exportMin ?? 0;
      const expMax = parameterDef?.max ?? conversionResult?.exportMax ?? Math.max(Math.abs(nv), 10);
      const span = Math.max(1e-6, Math.abs(expMax - expMin));

      if (span <= 1.05) {
        // Small linear scale e.g. [0, 1] or [0.00001, 1] (Threshold linear, Gate linear, Gain 0-1)
        toleranceUsed = 1e-4;
      } else if (span <= 12) {
        // Standard 0-10 scale
        toleranceUsed = 0.02;
      } else if (span <= 120) {
        // 0-100 percentage or dB scale (-100 to 0)
        toleranceUsed = 0.25;
      } else {
        // Large frequency or delay time scale (20 to 20000 Hz, 0 to 2000 ms)
        toleranceUsed = Math.max(1.0, span * 0.01);
      }

      // Check if one value is zero and other is non-zero (strict zero guard)
      if ((Math.abs(ev) < 1e-6 && Math.abs(nv) > 1e-4) || (Math.abs(nv) < 1e-6 && Math.abs(ev) > 1e-4)) {
        match = false;
      } else {
        const diff = Math.abs(nv - ev);
        match = diff <= toleranceUsed || String(expectedExportValue).trim().toLowerCase() === String(actualExportValue).trim().toLowerCase();
      }
    }
  } else {
    // String comparison (enums, discrete text)
    const expStr = String(expectedExportValue).trim().toLowerCase();
    const actStr = String(actualExportValue).trim().toLowerCase();
    match = expStr === actStr;
  }

  // 4. Status determination
  let status: ParameterVerificationResult["status"] = "SUCCESS";
  let reason: string | undefined = undefined;
  let warning: string | undefined = undefined;

  if (isMappingConfigSuspicious) {
    status = "FAIL_MAPPING_CONFIGURATION";
    reason = `Mapping configuration appears wrong: actual AT5 XML preserved ${ev} but current mapping expected ${nv} for ${parameterDef?.friendlyName || 'parameter'}.`;
  } else if (!match) {
    status = "FAIL";
    reason = `Expected ${intendedDisplayValue} (expected raw: ${expectedExportValue}) but exported value loads as ${conversionResult?.reverseDisplayValue || actualExportValue} (raw: "${actualExportValue}").`;
  } else if (isNearestBandMapping) {
    status = "SUCCESS_NEAREST_BAND";
    reason = `Mapped to nearest supported AT5 band ${nearestBandFreq}Hz.`;
  } else if (conversionResult?.clampApplied) {
    status = "DISPARITY";
    reason = `Value disparity (clamped): Intended: ${intendedDisplayValue}, actual exported value loads as ${conversionResult.reverseDisplayValue} due to physical limits of the gear.`;
    if (conversionResult.warnings && conversionResult.warnings.length > 0) {
      warning = conversionResult.warnings.join("; ");
    }
  } else if (conversionResult?.warnings && conversionResult.warnings.length > 0) {
    status = "WARNING";
    warning = conversionResult.warnings.join("; ");
    reason = warning;
  } else {
    status = "SUCCESS";
  }

  return {
    match,
    status,
    reason,
    warning,
    isAccidentalClampingTo1,
    isMappingConfigSuspicious,
    toleranceUsed,
  };
}

export function resolveParameterValue(
  value: unknown,
  min: number,
  max: number,
  transform?: VerifiedParamDef["transform"] | string,
  visualMin?: number,
  visualMax?: number,
  def?: any
): string | number | undefined {
  const res = convertParameterValueForExport({
    inputValue: value,
    parameterDef: def,
    conversionMode: transform,
    displayMin: visualMin,
    displayMax: visualMax,
    exportMin: min,
    exportMax: max,
    displayPrecision: def?.displayPrecision ?? def?.displayDecimalPlaces ?? def?.decimalPlaces,
    exportPrecision: def?.exportPrecision ?? def?.exportDecimalPlaces,
    exportDecimalPlaces: def?.exportPrecision ?? def?.exportDecimalPlaces,
  });

  if (typeof res.formattedExportValue === "string" && res.formattedExportValue !== "") {
    return res.formattedExportValue;
  }
  if (typeof res.finalExportValue === "number" && Number.isFinite(res.finalExportValue)) {
    return res.finalExportValue;
  }
  return undefined;
}

export function normalizeSettingsToCanonical(
  gearNameOrId: string | undefined,
  category: string,
  settings: Record<string, string | number> = {}
): Record<string, string | number> {
  const defs = getParameterDefinitions(gearNameOrId, category);
  if (!defs || defs.length === 0) {
    return settings;
  }

  const normalized: Record<string, string | number> = {};
  for (const [key, val] of Object.entries(settings)) {
    const cleanKey = key.toLowerCase().replace(/[^a-z0-9.]/g, "");
    
    const def = defs.find((d) => {
      const cleanFriendly = d.friendlyName.toLowerCase().replace(/[^a-z0-9.]/g, "");
      const cleanXml = d.xmlName.toLowerCase().replace(/[^a-z0-9.]/g, "");
      const cleanDisplay = (d.displayParameterName || "").toLowerCase().replace(/[^a-z0-9.]/g, "");
      const cleanCanonical = (d.canonicalParameterName || "").toLowerCase().replace(/[^a-z0-9.]/g, "");
      const cleanAliases = [
        ...(d.aliases ?? []),
        ...(d.savedAliases ?? []),
        ...(d.rawMappingAliases ?? []),
        ...(d.autoGeneratedAliases ?? []),
        ...(d.effectiveAliases ?? [])
      ].map((a) => a.toLowerCase().replace(/[^a-z0-9.]/g, ""));
      return (
        cleanFriendly === cleanKey ||
        cleanXml === cleanKey ||
        cleanDisplay === cleanKey ||
        cleanCanonical === cleanKey ||
        cleanAliases.includes(cleanKey)
      );
    });

    if (def) {
      normalized[def.friendlyName] = val;
    } else {
      normalized[key] = val;
    }
  }
  return normalized;
}

export function buildMappedParameterAttrs(
  gearNameOrId: string | undefined,
  category: string,
  settings: Record<string, unknown> = {}
): string {
  const defs = getParameterDefinitions(gearNameOrId, category);

  const canonicalSettings = normalizeSettingsToCanonical(gearNameOrId, category, settings as Record<string, string | number>);

  const normalisedSettings = new Map(
    Object.entries(canonicalSettings).map(([key, value]) => [normalise(key), value])
  );

  // Darrell 100 channel-aware mappings (Rule 6 & 7)
  const normGear = (gearNameOrId || "").toLowerCase().replace(/[^a-z0-9]/g, "");
  if (normGear === "darrell100") {
    let channelVal = (settings["Channel"] ?? settings["channel"] ?? settings["Channel_Darrell100"] ?? settings["channel_darrell100"]) as any;
    let isHighGainChannel = false;
    if (channelVal !== undefined) {
      const chStr = String(channelVal).toLowerCase();
      if (chStr === "2" || chStr.includes("lead") || chStr.includes("high") || chStr.includes("ch2") || chStr.includes("crunch")) {
        isHighGainChannel = true;
      }
    }

    const gainVal = (settings["Gain"] ?? settings["gain"] ?? settings["preamp"] ?? settings["PreAmp"] ?? settings["drive"] ?? settings["Drive"]) as any;
    const masterVal = (settings["Master"] ?? settings["master"] ?? settings["volume"] ?? settings["Volume"]) as any;

    if (isHighGainChannel) {
      if (gainVal !== undefined && normalisedSettings.get(normalise("Gain2_Darrell100")) === undefined) {
        normalisedSettings.set(normalise("Gain2_Darrell100"), gainVal);
      }
      if (masterVal !== undefined && normalisedSettings.get(normalise("Master2_Darrell100")) === undefined) {
        normalisedSettings.set(normalise("Master2_Darrell100"), masterVal);
      }
    } else {
      if (gainVal !== undefined && normalisedSettings.get(normalise("Gain1_Darrell100")) === undefined) {
        normalisedSettings.set(normalise("Gain1_Darrell100"), gainVal);
      }
      if (masterVal !== undefined && normalisedSettings.get(normalise("Master1_Darrell100")) === undefined) {
        normalisedSettings.set(normalise("Master1_Darrell100"), masterVal);
      }
    }

    if (channelVal !== undefined) {
      normalisedSettings.set(normalise("Channel_Darrell100"), channelVal);
    }
  }

  // Noise Gate Depth safety
  if (normalise(gearNameOrId || "") === "noise gate") {
    const hasDepth = ["depth", "reduction"].some(alias => normalisedSettings.has(normalise(alias)));
    if (!hasDepth) {
      normalisedSettings.set("depth", "-60");
    }
  }

  if (!defs.length) {
    return Object.entries(settings || {})
      .map(([key, value]) => `${compact(key)}="${escapeXmlAttr(value)}"`)
      .join(" ");
  }

  const attributes: { xmlName: string; attrValue: string; isDefault: boolean }[] = [];

  for (const def of defs) {
    const lookupNames = [
      def.friendlyName,
      def.xmlName,
      def.displayParameterName,
      def.canonicalParameterName,
      ...(def.aliases ?? []),
      ...(def.savedAliases ?? []),
      ...(def.rawMappingAliases ?? []),
      ...(def.autoGeneratedAliases ?? []),
      ...(def.effectiveAliases ?? [])
    ].filter(Boolean) as string[];
    let raw = lookupNames
      .map((name) => normalisedSettings.get(normalise(name)))
      .find((value) => value !== undefined);

    let isDefault = false;

    if (raw === undefined && gearNameOrId && (category === "rack" || category === "stomp") && gearNameOrId.toLowerCase().includes("graphic")) {
      const bandMatch = def.xmlName.match(/^Band(\d+)$/i);
      if (bandMatch) {
        const bandFreq = parseInt(bandMatch[1]);
        for (const [sKey, sVal] of normalisedSettings.entries()) {
          const hz = parseFrequencyToHz(sKey);
          if (hz !== null) {
            const closest = findClosestBand(hz);
            if (closest === bandFreq) {
              raw = sVal;
              break;
            }
          }
        }
      }
    }

    if (raw === undefined && def.defaultValue !== undefined) {
      raw = def.defaultValue;
      isDefault = true;
    }

    const resolved = resolveParameterValue(raw, def.min, def.max, def.transform, def.visualMin, def.visualMax, def);
    if (resolved === undefined) continue;

    const formattedValue = typeof resolved === "string"
      ? escapeXmlAttr(resolved)
      : String(Number(resolved.toFixed(6)));

    attributes.push({
      xmlName: def.xmlName,
      attrValue: formattedValue,
      isDefault
    });
  }

  const finalMap = new Map<string, typeof attributes[number]>();
  for (const attr of attributes) {
    const existing = finalMap.get(attr.xmlName);
    if (!existing || (existing.isDefault && !attr.isDefault)) {
      finalMap.set(attr.xmlName, attr);
    }
  }

  return Array.from(finalMap.values())
    .map(attr => `${attr.xmlName}="${attr.attrValue}"`)
    .join(" ");
}

export interface TestTranslationResult {
  inputValue: string | number;
  parsedNumericValue?: number | string;
  resolvedExportValue: string | number;
  conversionMode: string;
  isClamped: boolean;
  displayPrecision?: number;
  exportPrecision?: number;
  visualRange: { min: number; max: number; unit?: string; formattedMin?: string; formattedMax?: string };
  exportRange: { min: number; max: number; formattedMin?: string; formattedMax?: string };
  formulaDescription?: string;
  xmlPreview: string;
  reverseConvertedDisplayValue?: string;
  warnings?: string[];
}

export function testSingleParameterTranslation(
  paramDef: any,
  inputValue: string | number,
  gearContext?: { gearType?: string; gearDisplayName?: string; gearGuid?: string }
): TestTranslationResult {
  const warnings: string[] = [];

  const xmlAttr = paramDef.export?.name || paramDef.at5XmlAttributeName || paramDef.canonicalName || paramDef.displayName || paramDef.xmlName || "Param";
  const convMode = paramDef.conversion?.mode || paramDef.translationMode || paramDef.transform || paramDef.conversion || "direct";

  const res = convertParameterValueForExport({
    inputValue,
    parameterDef: paramDef,
    conversionMode: convMode,
    displayMin: paramDef.visual?.min ?? paramDef.displayMin ?? paramDef.visualMin,
    displayMax: paramDef.visual?.max ?? paramDef.displayMax ?? paramDef.visualMax,
    exportMin: paramDef.export?.min ?? paramDef.exportMin ?? paramDef.min,
    exportMax: paramDef.export?.max ?? paramDef.exportMax ?? paramDef.max,
    displayUnit: paramDef.visual?.unit ?? paramDef.displayUnit ?? paramDef.unit,
    displayPrecision: paramDef.displayPrecision ?? paramDef.displayDecimalPlaces ?? paramDef.decimalPlaces,
    exportPrecision: paramDef.exportPrecision ?? paramDef.exportDecimalPlaces,
    exportDecimalPlaces: paramDef.exportPrecision ?? paramDef.exportDecimalPlaces
  });

  if (!paramDef.export?.name && !paramDef.at5XmlAttributeName && !paramDef.xmlName) {
    warnings.push("No explicit AT5 XML attribute ID configured.");
  }

  // Check for bad / suspicious mapping configuration
  if (res.conversionMode === "db_to_linear" || paramDef.parameterKind === "gain_db") {
    if ((res.displayMin === res.exportMin && res.displayMax === res.exportMax) || (res.displayMin >= 0 && res.displayMax > 1 && res.displayMax <= 10)) {
      warnings.push(
        `CHECK / FAIL_MAPPING_CONFIGURATION: Visual range [${res.displayMin}, ${res.displayMax}] appears to contain raw AmpliTube float values. For db_to_linear, set UI Visual range to display dB values (e.g. -15 to +15 dB).`
      );
    }
  }

  if (res.warnings && res.warnings.length > 0) {
    warnings.push(...res.warnings);
  }

  const xmlPreview = `${xmlAttr}="${escapeXmlAttr(res.formattedExportValue)}"`;

  return {
    inputValue,
    parsedNumericValue: res.parsedNumericValue,
    resolvedExportValue: res.formattedExportValue,
    conversionMode: res.conversionMode,
    isClamped: res.clampApplied,
    displayPrecision: res.displayPrecision,
    exportPrecision: res.exportPrecision,
    visualRange: {
      min: res.displayMin,
      max: res.displayMax,
      unit: res.displayUnit,
      formattedMin: res.formattedVisualMin,
      formattedMax: res.formattedVisualMax
    },
    exportRange: {
      min: res.exportMin,
      max: res.exportMax,
      formattedMin: res.formattedExportMin,
      formattedMax: res.formattedExportMax
    },
    formulaDescription: paramDef.conversion?.formula || paramDef.helperDescription,
    xmlPreview,
    reverseConvertedDisplayValue: res.reverseDisplayValue,
    warnings: warnings.length > 0 ? warnings : undefined
  };
}
