// src/tests/amplitube5ExportEvidenceValidation.test.ts
// Unit test suite for WP-30 Stage 2 Slice 4B:
// AmpliTube 5 Export-Process Evidence, Clamping / Disparity Detection & Final PASS Boundary.
// Bound to frozen specification v0.1j Section 37, Activity WF-07, and Build Plan v0.1h WP-30.

import assert from "node:assert/strict";
import { describe, it } from "node:test";
import {
  AmpliTube5ValidationAdapter,
  PLATFORM_VALIDATION_STATUSES,
  translateStage12ExportEvidence,
  evaluateAmpliTube5ExportEvidence,
  type ExportProcessEvidence,
  type ParameterConversionRecord,
} from "../sound-engineer/validation/platform";

// Authoritative GUID fixtures from AT5 gear catalog
const STOMP_OVERSCREAM_GUID = "fa1de2e2-102b-4edf-b3b5-23ceaeddedf0"; // OverScream (Drive, Tone, Level 0-10)
const AMP_BRIT8000_GUID = "8fe96936-5178-4950-9b80-d89c32534bad";     // Brit 8000
const CAB_BRIT8000_GUID = "7c0b8ce1-cbb4-4e5b-9973-a572143ddb2b";     // 4x12 Brit 8000
const RACK_BLACK76_GUID = "e5a6190f-9031-4a30-8041-36ba95f9a2e1";     // Black 76

/**
 * Builds a valid AT5 preset XML matching canonical parser and module contracts.
 */
function createParamTestXml(options?: {
  stompGuid?: string;
  stompParams?: string;
  ampGuid?: string;
  ampParams?: string;
  cabGuid?: string;
  cabParams?: string;
  rackGuid?: string;
  rackParams?: string;
}): string {
  const stompGuid = options?.stompGuid ?? STOMP_OVERSCREAM_GUID;
  const stompParams = options?.stompParams ?? 'Drive="5.0" Tone="6.0" Level="7.0"';
  const ampGuid = options?.ampGuid ?? AMP_BRIT8000_GUID;
  const ampParams = options?.ampParams ?? 'Gain_BritishTubeLead1="6.0" Bass_BritishTubeLead1="5.0"';
  const cabGuid = options?.cabGuid ?? CAB_BRIT8000_GUID;
  const cabParams = options?.cabParams ?? 'Mic1Level="1.0"';
  const rackGuid = options?.rackGuid ?? RACK_BLACK76_GUID;
  const rackParams = options?.rackParams ?? 'Input="5.0" Output="5.0"';

  return `<?xml version="1.0" ?>
<Preset Version="2" Format="at5p" GUID="8fe96936-5178-4950-9b80-d89c32534bad" PresetBPM="120" ProgramChange="1">
    <Chain Preset="Chain11" DIBeforeAmp="0" />
    <Input Input="1" />
    <Tuner Bypass="1" Mute="0" OutputVolume="1" TunerType="354eca51-457a-41b7-917d-ce6117586905" />
    <StompA1 Bypass="0" Mute="0" OutputVolume="1" Stomp0="${stompGuid}">
        <Slot0 ${stompParams} />
    </StompA1>
    <AmpA Bypass="0" Mute="0" OutputVolume="1" Model="${ampGuid}">
        <Amp ${ampParams} />
    </AmpA>
    <CabA Bypass="0" Mute="0" OutputVolume="1" CabModel="${cabGuid}">
        <Cab ${cabParams} />
    </CabA>
    <RackA Bypass="0" Mute="0" OutputVolume="1" Stomp0="${rackGuid}">
        <Slot0 ${rackParams} />
    </RackA>
    <Output Output="1" />
</Preset>`;
}

/**
 * Creates clean complete evidence matching the 5 serialized parameters generated by createParamTestXml().
 */
function createCleanEvidence(): ExportProcessEvidence {
  return {
    parameterConversions: [
      {
        parameterId: "Drive",
        targetModuleId: STOMP_OVERSCREAM_GUID,
        sourceValue: 5.0,
        convertedValue: 5.0,
        serializedValue: "5.0",
        clampApplied: false,
        mappingStatus: "SUCCESS",
      },
      {
        parameterId: "Tone",
        targetModuleId: STOMP_OVERSCREAM_GUID,
        sourceValue: 6.0,
        convertedValue: 6.0,
        serializedValue: "6.0",
        clampApplied: false,
        mappingStatus: "SUCCESS",
      },
      {
        parameterId: "Level",
        targetModuleId: STOMP_OVERSCREAM_GUID,
        sourceValue: 7.0,
        convertedValue: 7.0,
        serializedValue: "7.0",
        clampApplied: false,
        mappingStatus: "SUCCESS",
      },
      {
        parameterId: "Gain_BritishTubeLead1",
        targetModuleId: AMP_BRIT8000_GUID,
        sourceValue: 6.0,
        convertedValue: 6.0,
        serializedValue: "6.0",
        clampApplied: false,
        mappingStatus: "SUCCESS",
      },
      {
        parameterId: "Bass_BritishTubeLead1",
        targetModuleId: AMP_BRIT8000_GUID,
        sourceValue: 5.0,
        convertedValue: 5.0,
        serializedValue: "5.0",
        clampApplied: false,
        mappingStatus: "SUCCESS",
      },
    ],
  };
}

describe("WP-30 Stage 2 Slice 4B: Export-Process Evidence, Clamping / Disparity Detection & Final PASS Boundary", () => {
  const adapter = new AmpliTube5ValidationAdapter();

  it("1. clean complete evidence + valid artifact yields PASS", async () => {
    const xml = createParamTestXml();
    const evidence = createCleanEvidence();

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.PASS);
    assert.equal(result.isSyntaxValid, true);
    assert.equal(result.processEvidenceEvaluated, true);
    assert.ok(result.parameterResults && result.parameterResults.length === 5);
    assert.ok(result.parameterResults.every((p) => p.status === PLATFORM_VALIDATION_STATUSES.PASS));
    assert.ok(result.diagnostics.some((d) => d.includes("EXPORT_EVIDENCE_VERIFIED")));
  });

  it("2. exportEvidence absent yields NOT_VERIFIABLE", async () => {
    const xml = createParamTestXml();

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      // exportEvidence intentionally omitted
    });

    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.NOT_VERIFIABLE);
    assert.equal(result.processEvidenceEvaluated, false);
    assert.ok(result.diagnostics.some((d) => d.includes("EXPORT_EVIDENCE_NOT_EVALUATED")));
  });

  it("3. incomplete evidence yields NOT_VERIFIABLE", async () => {
    const xml = createParamTestXml();
    // Only 1 record provided for OverScream Drive, omitting all other parameters
    const incompleteEvidence: ExportProcessEvidence = {
      parameterConversions: [
        {
          parameterId: "Drive",
          targetModuleId: STOMP_OVERSCREAM_GUID,
          sourceValue: 5.0,
          convertedValue: 5.0,
          serializedValue: "5.0",
          clampApplied: false,
          mappingStatus: "SUCCESS",
        },
      ],
    };

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: incompleteEvidence,
    });

    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.NOT_VERIFIABLE);
    assert.equal(result.processEvidenceEvaluated, true);
    assert.ok(result.diagnostics.some((d) => d.includes("INCOMPLETE_PROCESS_EVIDENCE")));
    const toneParam = result.parameterResults?.find((p) => p.parameterId === "Tone");
    assert.equal(toneParam?.status, PLATFORM_VALIDATION_STATUSES.NOT_VERIFIABLE);
  });

  it("4. source value clamped into legal XML value is detected", async () => {
    // OverScream Drive serialized as 10.0 (legal). But source was 12.0 and clamped to 10.0.
    const xml = createParamTestXml({ stompParams: 'Drive="10.0" Tone="6.0" Level="7.0"' });
    const evidence = createCleanEvidence();
    // Update Drive record with clamping evidence
    const driveRec = evidence.parameterConversions.find((r) => r.parameterId === "Drive")!;
    (driveRec as any).sourceValue = 12.0;
    (driveRec as any).convertedValue = 10.0;
    (driveRec as any).serializedValue = "10.0";
    (driveRec as any).clampApplied = true;
    (driveRec as any).preClampValue = 12.0;
    (driveRec as any).postClampValue = 10.0;

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    // Serialized artifact is legal, but process has clamping -> overall DISPARITY
    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.DISPARITY);
    assert.equal(result.processEvidenceEvaluated, true);
    const driveResult = result.parameterResults?.find((p) => p.parameterId === "Drive");
    assert.ok(driveResult);
    assert.equal(driveResult.status, PLATFORM_VALIDATION_STATUSES.DISPARITY);
    assert.equal(driveResult.clampApplied, true);
    assert.equal(driveResult.sourceValue, 12.0);
    assert.ok(driveResult.message?.includes("Pre-export clamping detected"));
  });

  it("5. clamped legal artifact does not PASS", async () => {
    const xml = createParamTestXml({ stompParams: 'Drive="10.0" Tone="6.0" Level="7.0"' });
    const evidence = createCleanEvidence();
    const driveRec = evidence.parameterConversions.find((r) => r.parameterId === "Drive")!;
    (driveRec as any).sourceValue = 12.0;
    (driveRec as any).convertedValue = 10.0;
    (driveRec as any).serializedValue = "10.0";
    (driveRec as any).clampApplied = true;

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    assert.notEqual(result.overallStatus, PLATFORM_VALIDATION_STATUSES.PASS);
    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.DISPARITY);
  });

  it("6. source value exactly at boundary with no clamp remains clean", async () => {
    // Drive is exactly at max boundary (10.0), but source was 10.0 and clampApplied is false
    const xml = createParamTestXml({ stompParams: 'Drive="10.0" Tone="6.0" Level="7.0"' });
    const evidence = createCleanEvidence();
    const driveRec = evidence.parameterConversions.find((r) => r.parameterId === "Drive")!;
    (driveRec as any).sourceValue = 10.0;
    (driveRec as any).convertedValue = 10.0;
    (driveRec as any).serializedValue = "10.0";
    (driveRec as any).clampApplied = false;

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.PASS);
    const driveResult = result.parameterResults?.find((p) => p.parameterId === "Drive");
    assert.equal(driveResult?.status, PLATFORM_VALIDATION_STATUSES.PASS);
    assert.equal(driveResult?.clampApplied, false);
  });

  it("7. expected export value differs from XML value -> non-PASS factual defect (FAIL)", async () => {
    // Evidence says expected export value was 5.0, but actual XML has 8.0
    const xml = createParamTestXml({ stompParams: 'Drive="8.0" Tone="6.0" Level="7.0"' });
    const evidence = createCleanEvidence(); // Expects Drive 5.0

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.FAIL);
    const driveResult = result.parameterResults?.find((p) => p.parameterId === "Drive");
    assert.equal(driveResult?.status, PLATFORM_VALIDATION_STATUSES.FAIL);
    assert.ok(driveResult?.message?.includes("Export disparity: evidence expected"));
  });

  it("8. existing mapping status FAIL -> overall FAIL", async () => {
    const xml = createParamTestXml();
    const evidence = createCleanEvidence();
    const driveRec = evidence.parameterConversions.find((r) => r.parameterId === "Drive")!;
    (driveRec as any).mappingStatus = "FAIL";
    (driveRec as any).diagnosticNote = "Translation failed";

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.FAIL);
    const driveResult = result.parameterResults?.find((p) => p.parameterId === "Drive");
    assert.equal(driveResult?.status, PLATFORM_VALIDATION_STATUSES.FAIL);
    assert.ok(driveResult?.message?.includes("Export mapping failure [FAIL]"));
  });

  it("9. FAIL_MAPPING_CONFIGURATION -> overall FAIL", async () => {
    const xml = createParamTestXml();
    const evidence = createCleanEvidence();
    const driveRec = evidence.parameterConversions.find((r) => r.parameterId === "Drive")!;
    (driveRec as any).mappingStatus = "FAIL_MAPPING_CONFIGURATION";
    (driveRec as any).diagnosticNote = "Invalid parameter mapping curve";

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.FAIL);
    const driveResult = result.parameterResults?.find((p) => p.parameterId === "Drive");
    assert.equal(driveResult?.status, PLATFORM_VALIDATION_STATUSES.FAIL);
    assert.ok(driveResult?.message?.includes("FAIL_MAPPING_CONFIGURATION"));
  });

  it("10. DISPARITY source status preserved/mapped correctly", async () => {
    const xml = createParamTestXml();
    const evidence = createCleanEvidence();
    const driveRec = evidence.parameterConversions.find((r) => r.parameterId === "Drive")!;
    (driveRec as any).mappingStatus = "DISPARITY";
    (driveRec as any).diagnosticNote = "Approximate curve used";

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.DISPARITY);
    const driveResult = result.parameterResults?.find((p) => p.parameterId === "Drive");
    assert.equal(driveResult?.status, PLATFORM_VALIDATION_STATUSES.DISPARITY);
  });

  it("11. duplicate evidence does not get arbitrarily selected", async () => {
    const xml = createParamTestXml();
    const evidence = createCleanEvidence();
    // Add duplicate record for OverScream Drive
    (evidence as any).parameterConversions.push({
      parameterId: "Drive",
      targetModuleId: STOMP_OVERSCREAM_GUID,
      sourceValue: 5.0,
      convertedValue: 5.0,
      serializedValue: "5.0",
      clampApplied: false,
      mappingStatus: "SUCCESS",
    });

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.NOT_VERIFIABLE);
    const driveResult = result.parameterResults?.find((p) => p.parameterId === "Drive");
    assert.equal(driveResult?.status, PLATFORM_VALIDATION_STATUSES.NOT_VERIFIABLE);
    assert.ok(driveResult?.message?.includes("Duplicate export conversion evidence detected"));
  });

  it("12. orphan evidence is reported and prevents PASS (yields NOT_VERIFIABLE)", async () => {
    const xml = createParamTestXml();
    const evidence = createCleanEvidence();
    // Add orphan record for non-existent parameter
    (evidence as any).parameterConversions.push({
      parameterId: "NonExistentKnob",
      targetModuleId: STOMP_OVERSCREAM_GUID,
      sourceValue: 3.0,
      convertedValue: 3.0,
      serializedValue: "3.0",
      clampApplied: false,
      mappingStatus: "SUCCESS",
    });

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    // Unexplained orphan evidence prevents PASS and returns NOT_VERIFIABLE
    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.NOT_VERIFIABLE);
    assert.notEqual(result.overallStatus, PLATFORM_VALIDATION_STATUSES.PASS);
    assert.ok(result.diagnostics.some((d) => d.includes("ORPHAN_EVIDENCE") && d.includes("NonExistentKnob")));
  });

  it("13. ambiguous correlation -> NOT_VERIFIABLE", () => {
    // When serialized parameters exist but evidence has missing records
    const evalResult = evaluateAmpliTube5ExportEvidence(
      [
        {
          parameterId: "Drive",
          moduleId: STOMP_OVERSCREAM_GUID,
          status: PLATFORM_VALIDATION_STATUSES.PASS,
          serializedValue: "5.0",
        },
      ],
      { parameterConversions: [] }
    );

    assert.equal(evalResult.overallProcessStatus, PLATFORM_VALIDATION_STATUSES.NOT_VERIFIABLE);
    assert.equal(evalResult.missingEvidenceCount, 1);
  });

  it("14. every required serialized parameter must be evidence-covered for PASS", async () => {
    const xml = createParamTestXml();
    const evidence = createCleanEvidence();
    // Remove Tone parameter record from evidence
    (evidence as any).parameterConversions = evidence.parameterConversions.filter(
      (r) => r.parameterId !== "Tone"
    );

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    assert.notEqual(result.overallStatus, PLATFORM_VALIDATION_STATUSES.PASS);
    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.NOT_VERIFIABLE);
  });

  it("15. empty evidence array does not mean complete verification", async () => {
    const xml = createParamTestXml();
    const emptyEvidence: ExportProcessEvidence = { parameterConversions: [] };

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: emptyEvidence,
    });

    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.NOT_VERIFIABLE);
    assert.equal(result.processEvidenceEvaluated, true);
    assert.ok(result.diagnostics.some((d) => d.includes("INCOMPLETE_PROCESS_EVIDENCE")));
  });

  it("16. clean module/parameter validation remains intact", async () => {
    const xml = createParamTestXml();
    const evidence = createCleanEvidence();

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    assert.ok(result.moduleResults && result.moduleResults.length === 4);
    assert.ok(result.moduleResults.every((m) => m.status === PLATFORM_VALIDATION_STATUSES.PASS));
    assert.ok(result.parameterResults && result.parameterResults.length === 5);
  });

  it("17. any existing structural/module/parameter FAIL still dominates process evaluation", async () => {
    // Serialized XML has invalid Drive 999.0 (exceeds exportMax 10)
    const xml = createParamTestXml({ stompParams: 'Drive="999.0" Tone="6.0" Level="7.0"' });
    const evidence = createCleanEvidence();
    const driveRec = evidence.parameterConversions.find((r) => r.parameterId === "Drive")!;
    (driveRec as any).convertedValue = 999.0;
    (driveRec as any).serializedValue = "999.0";

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.FAIL);
    const driveResult = result.parameterResults?.find((p) => p.parameterId === "Drive");
    assert.equal(driveResult?.status, PLATFORM_VALIDATION_STATUSES.FAIL);
    assert.ok(driveResult?.message?.includes("exceeds authoritative exportMax"));
  });

  it("18. processEvidenceEvaluated is true only when evidence was actually evaluated", async () => {
    const xml = createParamTestXml();

    // A: Without evidence
    const noEvResult = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
    });
    assert.equal(noEvResult.processEvidenceEvaluated, false);

    // B: With evidence
    const evResult = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: createCleanEvidence(),
    });
    assert.equal(evResult.processEvidenceEvaluated, true);
  });

  it("19. full PASS requires zero NOT_VERIFIABLE dimensions", async () => {
    const xml = createParamTestXml();
    const evidence = createCleanEvidence();

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.PASS);
    assert.equal(
      result.parameterResults?.some((p) => p.status === PLATFORM_VALIDATION_STATUSES.NOT_VERIFIABLE),
      false
    );
    assert.equal(
      result.moduleResults?.some((m) => m.status === PLATFORM_VALIDATION_STATUSES.NOT_VERIFIABLE),
      false
    );
  });

  it("20. technology-neutral contract remains free of AT5 exporter-specific fields", () => {
    // Assert that ExportProcessEvidence and ParameterConversionRecord do not contain AT5 XML names
    const neutralRecord: ParameterConversionRecord = {
      parameterId: "Drive",
      sourceValue: 5.0,
      convertedValue: 5.0,
      clampApplied: false,
    };

    assert.equal(neutralRecord.parameterId, "Drive");
    assert.equal(neutralRecord.clampApplied, false);
    assert.equal((neutralRecord as any).at5XmlAttributeName, undefined);
    assert.equal((neutralRecord as any).ikmpakCandidate, undefined);
  });

  it("21. translateStage12ExportEvidence maps Stage-12 diagnostics correctly", () => {
    const stage12Mock = {
      exported_chain: [
        {
          actual_exported_guid: STOMP_OVERSCREAM_GUID,
          slot_section: "Stomp0",
          parameter_details: [
            {
              parameter: "Drive",
              matched_export_parameter_name: "Drive",
              input_value: 12.0,
              converted_raw_value: 10.0,
              final_export_value: 10.0,
              clamp_applied: true,
              pre_clamp_value: 12.0,
              post_clamp_value: 10.0,
              mapping_status: "SUCCESS",
              display_value: "12.0",
            },
          ],
        },
      ],
    };

    const evidence = translateStage12ExportEvidence(stage12Mock);
    assert.equal(evidence.parameterConversions.length, 1);
    const rec = evidence.parameterConversions[0];
    assert.equal(rec.parameterId, "Drive");
    assert.equal(rec.targetModuleId, STOMP_OVERSCREAM_GUID);
    assert.equal(rec.sourceValue, 12.0);
    assert.equal(rec.convertedValue, 10.0);
    assert.equal(rec.clampApplied, true);
    assert.equal(rec.preClampValue, 12.0);
    assert.equal(rec.postClampValue, 10.0);
    assert.equal(rec.mappingStatus, "SUCCESS");
  });

  it("22. mixed DISPARITY + NOT_VERIFIABLE yields overall NOT_VERIFIABLE (FAIL > NOT_VERIFIABLE > DISPARITY)", async () => {
    // OverScream Drive has factual clamping (12.0 clamped to 10.0 -> DISPARITY)
    // Tone parameter evidence is omitted -> NOT_VERIFIABLE
    const xml = createParamTestXml({ stompParams: 'Drive="10.0" Tone="6.0" Level="7.0"' });
    const evidence = createCleanEvidence();

    // 1. Configure Drive with factual clamping
    const driveRec = evidence.parameterConversions.find((r) => r.parameterId === "Drive")!;
    (driveRec as any).sourceValue = 12.0;
    (driveRec as any).convertedValue = 10.0;
    (driveRec as any).serializedValue = "10.0";
    (driveRec as any).clampApplied = true;
    (driveRec as any).preClampValue = 12.0;
    (driveRec as any).postClampValue = 10.0;

    // 2. Remove Tone record from evidence so it becomes NOT_VERIFIABLE
    (evidence as any).parameterConversions = evidence.parameterConversions.filter(
      (r) => r.parameterId !== "Tone"
    );

    const result = await adapter.validatePresetExport({
      targetPlatformId: "amplitube-5",
      serializedPreset: xml,
      exportEvidence: evidence,
    });

    // Individual parameter assertions:
    const driveParam = result.parameterResults?.find((p) => p.parameterId === "Drive");
    assert.ok(driveParam);
    assert.equal(driveParam.status, PLATFORM_VALIDATION_STATUSES.DISPARITY);
    assert.equal(driveParam.clampApplied, true);

    const toneParam = result.parameterResults?.find((p) => p.parameterId === "Tone");
    assert.ok(toneParam);
    assert.equal(toneParam.status, PLATFORM_VALIDATION_STATUSES.NOT_VERIFIABLE);

    // Overall verdict assertion:
    // NOT_VERIFIABLE dominates DISPARITY because a mandatory dimension remains unresolved.
    assert.equal(result.overallStatus, PLATFORM_VALIDATION_STATUSES.NOT_VERIFIABLE);
    assert.notEqual(result.overallStatus, PLATFORM_VALIDATION_STATUSES.DISPARITY);
    assert.notEqual(result.overallStatus, PLATFORM_VALIDATION_STATUSES.PASS);
  });
});
